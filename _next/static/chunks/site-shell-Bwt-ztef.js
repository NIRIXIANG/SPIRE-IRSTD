        <section id="method" class="content-block" aria-labelledby="overview" data-qa="method">
          <div>
            <h2 id="overview" class="section-title">Overview</h2>
            <p class="paragraph">
              Infrared small target detection is commonly framed as dense mask reconstruction, with a decoder
              progressively restoring spatial resolution. SPIRE revisits that choice: when the operational goal is
              reliable centroid localization, supervision, representation, and output can all be centered on a
              probabilistic response instead of a reconstructed contour.
            </p>
            <p class="paragraph">
              The method follows three steps: construct a structured response target from each centroid annotation,
              regress the response map on a fixed high-resolution branch, and recover target coordinates through
              local-maximum detection and sub-pixel refinement. The paper figure above opens at full resolution.
            </p>
          </div>

          <div class="method-flow" aria-label="Three stages of SPIRE">
            <div>
              <span>01</span>
              <strong>Single-Point Supervision</strong>
              <p>Construct a compact, center-enhanced regression target from each annotated centroid.</p>
            </div>
            <div>
              <span>02</span>
              <strong>Probabilistic Response Encoding</strong>
              <p>Regress the response on a fixed high-resolution branch without a decoder or skip connections.</p>
            </div>
            <div>
              <span>03</span>
              <strong>Peak-Based Localization</strong>
              <p>Read target centroids directly through local maxima and sub-pixel refinement.</p>
            </div>
          </div>
        </section>

